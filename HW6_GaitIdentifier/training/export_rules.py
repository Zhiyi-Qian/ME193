"""
Turns model1.joblib and model2.joblib into plain if/else Python code (gait_rules.py).
The live App then needs no scikit-learn, numpy, or joblib, just the standard library.

Usage (in the folder with the .joblib files):  python3 export_rules.py
"""
import joblib
from sklearn.tree import _tree


def tree_to_code(clf, names, func_name):
    t = clf.tree_
    lines = [f"def {func_name}(f):"]

    def walk(node, depth):
        ind = "    " * depth
        if t.feature[node] != _tree.TREE_UNDEFINED:
            name = str(names[t.feature[node]])
            thr = float(t.threshold[node])
            lines.append(f"{ind}if f[{name!r}] <= {thr!r}:")
            walk(t.children_left[node], depth + 1)
            lines.append(f"{ind}else:")
            walk(t.children_right[node], depth + 1)
        else:
            label = str(clf.classes_[t.value[node][0].argmax()])
            lines.append(f"{ind}return {label!r}")

    walk(0, 1)
    return "\n".join(lines)


m1 = joblib.load("model1.joblib")
m2 = joblib.load("model2.joblib")
axis = m1["axis"]

code = [
    '"""Auto-generated by export_rules.py. Do not edit by hand."""',
    f"MODEL1_AXIS = {axis!r}",
    "",
    "# Model 1: peak acceleration on one axis only",
    tree_to_code(m1["model"], [f"peak_{axis}"], "model1"),
    "",
    "# Model 2: all IMU outputs",
    tree_to_code(m2["model"], m2["features"], "model2"),
    "",
]
with open("gait_rules.py", "w") as fh:
    fh.write("\n".join(code))
print("Wrote gait_rules.py")
print("\n".join(code))
